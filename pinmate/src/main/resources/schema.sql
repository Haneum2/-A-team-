-- 회원 테이블 (SQL Developer 등에서 한 번 실행)
CREATE TABLE MEMBER (
    USER_ID   VARCHAR2(50)  PRIMARY KEY,
    PASSWORD  VARCHAR2(100) NOT NULL,   -- BCrypt 해시(60자)가 저장됨
    REG_DATE  DATE          DEFAULT SYSDATE NOT NULL
);

-- 투자성향 진단 결과 (진단할 때마다 한 행씩 저장, 가장 최근 행이 현재 투자성향)
CREATE SEQUENCE INVEST_RESULT_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE INVEST_RESULT (
    RESULT_ID      NUMBER        PRIMARY KEY,
    USER_ID        VARCHAR2(50)  NOT NULL REFERENCES MEMBER(USER_ID),
    INVEST_TYPE    VARCHAR2(20)  NOT NULL,   -- SHORT(단타) / LONG(장투) / DIVIDEND(배당) / STABLE(안정)
    SCORE_SHORT    NUMBER(2)     NOT NULL,
    SCORE_LONG     NUMBER(2)     NOT NULL,
    SCORE_DIVIDEND NUMBER(2)     NOT NULL,
    SCORE_STABLE   NUMBER(2)     NOT NULL,
    DIAG_DATE      DATE          DEFAULT SYSDATE NOT NULL
);
