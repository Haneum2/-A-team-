-- 관심종목: 회원이 관심 있는 종목. 한 회원이 같은 종목을 두 번 등록할 수 없다.
CREATE SEQUENCE WATCHLIST_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE WATCHLIST (
    WATCH_ID    NUMBER         PRIMARY KEY,
    USER_ID     VARCHAR2(50)   NOT NULL REFERENCES MEMBER(USER_ID),
    STOCK_CODE  VARCHAR2(20)   NOT NULL,
    STOCK_NAME  VARCHAR2(100)  NOT NULL,
    REG_DATE    DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT UQ_WATCHLIST_USER_STOCK UNIQUE (USER_ID, STOCK_CODE)
);
